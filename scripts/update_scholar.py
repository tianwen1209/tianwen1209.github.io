"""Fetch the "Cited by" table from a Google Scholar profile and write data/scholar.js.

Usage: python scripts/update_scholar.py <scholar_user_id> <output_js_path>

If Scholar cannot be reached or the page layout is not recognised (for example a
CAPTCHA page), the script leaves the existing file untouched and exits 0, so the
site keeps showing the last good numbers.
"""
import datetime
import json
import sys

import requests
from bs4 import BeautifulSoup

HEADERS = {
    "User-Agent": (
        "Mozilla/5.0 (Windows NT 10.0; Win64; x64) AppleWebKit/537.36 "
        "(KHTML, like Gecko) Chrome/124.0 Safari/537.36"
    ),
    "Accept-Language": "en-US,en;q=0.9",
}


def to_int(text):
    digits = "".join(ch for ch in text if ch.isdigit())
    return int(digits) if digits else 0


def fetch_stats(user_id):
    url = f"https://scholar.google.com/citations?user={user_id}&hl=en"
    resp = requests.get(url, headers=HEADERS, timeout=30)
    resp.raise_for_status()
    soup = BeautifulSoup(resp.text, "html.parser")

    table = soup.select_one("#gsc_rsb_st")
    if table is None:
        raise ValueError("citation table #gsc_rsb_st not found (blocked or layout changed)")

    columns = [th.get_text(strip=True) for th in table.select("thead th")][1:]
    rows = []
    for tr in table.select("tbody tr"):
        label = tr.select_one(".gsc_rsb_sc1")
        values = [to_int(td.get_text()) for td in tr.select(".gsc_rsb_std")]
        if label and values:
            rows.append({"label": label.get_text(strip=True), "values": values})
    if not columns or not rows:
        raise ValueError("citation table is empty")

    return {
        "profile": url,
        "columns": columns,
        "rows": rows,
        "updated": datetime.date.today().isoformat(),
    }


def main():
    user_id, out_path = sys.argv[1], sys.argv[2]
    try:
        stats = fetch_stats(user_id)
    except Exception as exc:  # keep the last good data on any failure
        print(f"::warning::Google Scholar update skipped: {exc}")
        return

    # Only rewrite the file when the numbers change, so the date does not
    # create a new commit every day.
    try:
        with open(out_path, encoding="utf-8") as f:
            old = f.read()
        start = old.index("{")
        old_stats = json.loads(old[start:old.rindex("}") + 1])
    except (OSError, ValueError):
        old_stats = None
    if old_stats and {k: old_stats.get(k) for k in ("columns", "rows")} == {
        k: stats[k] for k in ("columns", "rows")
    }:
        print("Scholar stats unchanged.")
        return

    with open(out_path, "w", encoding="utf-8") as f:
        f.write("// Generated by scripts/update_scholar.py. Do not edit by hand.\n")
        f.write("window.SCHOLAR_STATS = ")
        json.dump(stats, f, ensure_ascii=False, indent=2)
        f.write(";\n")
    print("Scholar stats updated:", json.dumps(stats["rows"]))


if __name__ == "__main__":
    main()
